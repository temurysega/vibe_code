// «Сегодня» в расписании (рецензия 22 ноября, п. 4): день без занятий и закончившийся день — разные ответы.
// Раньше экран, сам перешедший на следующую неделю, терял сегодняшний день и писал «Сегодня пар нет»
// даже вечером после пар. Модуль общий для экрана и теста.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { todayState, todayHead } from '../public/js/shared/today.js';

const at = (date, hhmm) => { const [h, m] = hhmm.split(':').map(Number); return { date, minutes: h * 60 + m }; };
const lesson = (start, end, status = 'normal') => ({ start, end, status });
const day = (date, items, holiday = null) => ({ date, holiday, items });
const head = (d, now) => todayHead(todayState(d, now));

test('пары ещё впереди или идут — отметки нет', () => {
  const d = day('2026-11-20', [lesson('09:00', '10:20'), lesson('12:40', '14:00')]);
  assert.equal(head(d, at('2026-11-20', '08:00')), '');
  assert.equal(head(d, at('2026-11-20', '13:00')), '', 'вторая пара идёт');
});

test('все пары прошли — «Сегодня занятия закончились» со временем, а не «пар нет»', () => {
  const d = day('2026-11-20', [lesson('09:00', '10:20'), lesson('12:40', '14:00')]);
  assert.equal(head(d, at('2026-11-20', '14:00')), 'Сегодня занятия закончились в 14:00');
  assert.equal(head(d, at('2026-11-20', '23:30')), 'Сегодня занятия закончились в 14:00');
});

test('занятий не было — «Сегодня пар нет»; выходной и отменённые пары называются', () => {
  assert.equal(head(day('2026-11-19', []), at('2026-11-19', '12:00')), 'Сегодня пар нет');
  assert.equal(head(null, at('2026-11-22', '12:00')), 'Сегодня пар нет', 'воскресенье не входит в учебную неделю');
  assert.equal(head(day('2026-11-04', [], 'День народного единства'), at('2026-11-04', '12:00')), 'Сегодня пар нет — день народного единства');
  const off = day('2026-11-18', [lesson('09:00', '10:20', 'cancelled'), lesson('10:30', '11:50', 'moved')]);
  assert.equal(head(off, at('2026-11-18', '08:00')), 'Сегодня пар нет — занятия отменены или перенесены');
});

test('отменённая пара не продлевает учебный день, перенесённая сюда — считается', () => {
  const d = day('2026-11-20', [lesson('09:00', '10:20'), lesson('15:40', '17:00', 'cancelled')]);
  assert.equal(head(d, at('2026-11-20', '11:00')), 'Сегодня занятия закончились в 10:20');
  const movedIn = day('2026-11-20', [lesson('09:00', '10:20'), lesson('15:40', '17:00', 'moved-in'), lesson('17:10', '18:30', 'extra')]);
  assert.equal(head(movedIn, at('2026-11-20', '11:00')), '');
  assert.equal(head(movedIn, at('2026-11-20', '18:30')), 'Сегодня занятия закончились в 18:30');
});

test('день из другой даты не выдаётся за сегодняшний', () => {
  assert.equal(todayState(day('2026-11-20', [lesson('09:00', '10:20')]), at('2026-11-21', '12:00')).state, 'none');
});
